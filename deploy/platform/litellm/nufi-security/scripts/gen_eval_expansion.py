def validate_entries(entries):
    errors = []
    for e in entries:
        q = e["question"]
        for ent in e["pii_entities"]:
            actual = q[ent["start"]:ent["end"]]
            if actual != ent["value"]:
                errors.append(
                    f'{e["id"]}: expected "{ent["value"]}" at [{ent["start"]}:{ent["end"]}], '
                    f'got "{actual}"'
                )
    return errors


def main():
    entries = generate_entries()

    # Validate
    errors = validate_entries(entries)
    if errors:
        print("VALIDATION ERRORS:")
        for err in errors:
            print(f"  {err}")
        raise SystemExit(1)

    # Check count
    if len(entries) != 85:
        print(f"ERROR: Expected 85 entries, got {len(entries)}")
        raise SystemExit(1)

    # Check IDs
    expected_ids = [f"pii_qa_{i:03d}" for i in range(171, 256)]
    actual_ids = [e["id"] for e in entries]
    if actual_ids != expected_ids:
        print(f"ERROR: ID mismatch. First: {actual_ids[0]}, Last: {actual_ids[-1]}")
        raise SystemExit(1)

    # Check long document entries
    long_entries = [e for e in entries if len(e["question"]) >= 2000]
    print(f"Long document entries (2000+ chars): {len(long_entries)}")
    for e in long_entries:
        print(f"  {e['id']}: {len(e['question'])} chars")

    # Append to file
    with open(DATA_FILE, "a", encoding="utf-8") as f:
        for e in entries:
            f.write(json.dumps(e, ensure_ascii=False) + "\n")

    print(f"\nSuccessfully appended {len(entries)} entries to {DATA_FILE}")

    # Verify total
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        total = sum(1 for _ in f)
    print(f"Total lines in file: {total}")


if __name__ == "__main__":
    main()
