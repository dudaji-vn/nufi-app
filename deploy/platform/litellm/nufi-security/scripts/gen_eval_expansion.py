def make_entity(question: str, pii_type: str, value: str) -> dict:
    start = question.index(value)
    end = start + len(value)
    return {"type": pii_type, "value": value, "start": start, "end": end}

def entry(id_num: int, question: str, expected_answer: str, entities_spec: list, category: str) -> dict:
    """entities_spec: list of (type, value) tuples"""
    pii_entities = []
    for pii_type, value in entities_spec:
        ent = make_entity(question, pii_type, value)
        pii_entities.append(ent)
    return {
        "id": f"pii_qa_{id_num:03d}",
        "question": question,
        "expected_answer": expected_answer,
        "pii_entities": pii_entities,
        "category": category,
    }

